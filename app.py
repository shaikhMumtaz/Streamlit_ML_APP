"""
Streamlit interface for the Dry Bean multi-class classification project.

Run after training:
  streamlit run app.py
"""
from pathlib import Path
import joblib
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
from sklearn.metrics import (
    accuracy_score, roc_auc_score, precision_score, recall_score,
    f1_score, matthews_corrcoef, confusion_matrix, classification_report,
    ConfusionMatrixDisplay
)

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT / "model"
MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "KNN": "knn.joblib",
    "Gaussian Naive Bayes": "gaussian_naive_bayes.joblib",
    "Support Vector Machine": "support_vector_machine.joblib",
}


@st.cache_resource
def load_bundle(filename):
    path = MODEL_DIR / filename
    if not path.exists():
        return None
    return joblib.load(path)


@st.cache_data
def load_saved_metrics():
    path = MODEL_DIR / "metrics.csv"
    return pd.read_csv(path) if path.exists() else None


st.set_page_config(
    page_title="BeanClassify | ML Model Explorer",
    page_icon="🌱",
    layout="wide"
)

st.title("🌱 BeanClassify")
st.caption("A multi-model machine learning explorer for dry bean classification")
st.markdown(
    "Compare five classification algorithms, upload labelled test data, "
    "and inspect model predictions and evaluation results."
)

with st.sidebar:
    st.header("Project information")
    st.write("**Dataset:** UCI Dry Bean")
    st.write("**Task:** 7-class classification")
    st.write("**Algorithms:** 5")
    st.divider()
    page = st.radio("Navigate", ["Evaluate uploaded data", "Saved model comparison"])
    st.caption("Upload a CSV containing the 16 feature columns and the actual `Class` column.")

if page == "Saved model comparison":
    st.subheader("Model performance comparison")
    metrics = load_saved_metrics()
    if metrics is None:
        st.warning("No trained model results found. Run `python train_models.py` first.")
    else:
        st.dataframe(
            metrics.style.format({c: "{:.4f}" for c in metrics.columns if c != "Model"}),
            use_container_width=True,
            hide_index=True
        )
        chart_data = metrics.set_index("Model")[["Accuracy", "AUC", "Precision", "Recall", "F1", "MCC"]]
        st.bar_chart(chart_data)
        winner = metrics.sort_values(["F1", "MCC"], ascending=False).iloc[0]
        st.success(
            f"Highest macro F1 score: **{winner['Model']}** "
            f"(F1 = {winner['F1']:.4f}). Use your full metric results when deciding the overall winner."
        )
else:
    st.subheader("1. Upload your labelled test CSV")
    uploaded = st.file_uploader("Choose test_data.csv", type=["csv"])
    if uploaded is None:
        st.info("Use the `test_data.csv` generated by train_models.py, or upload another compatible labelled test CSV.")
        st.stop()

    try:
        data = pd.read_csv(uploaded)
    except Exception as exc:
        st.error(f"Could not read this CSV: {exc}")
        st.stop()

    if data.empty:
        st.error("The uploaded CSV is empty.")
        st.stop()

    st.write(f"Uploaded data: **{len(data):,} rows × {len(data.columns)} columns**")
    st.dataframe(data.head(8), use_container_width=True)

    st.subheader("2. Choose a classification model")
    model_name = st.selectbox("Model", list(MODEL_FILES.keys()))
    bundle = load_bundle(MODEL_FILES[model_name])
    if bundle is None:
        st.error("Trained model files are missing. Run `python train_models.py` and upload the model folder to GitHub.")
        st.stop()

    feature_cols = bundle["feature_columns"]
    target_col = bundle["target_column"]
    missing = [col for col in feature_cols if col not in data.columns]
    if missing:
        st.error("Missing required feature columns: " + ", ".join(missing))
        st.stop()

    X = data[feature_cols].apply(pd.to_numeric, errors="coerce")
    if X.isna().all(axis=1).any():
        st.error("At least one row contains no usable numeric feature values.")
        st.stop()

    pipeline = bundle["pipeline"]
    predictions = pipeline.predict(X)
    result = data.copy()
    result["Predicted_Class"] = predictions

    st.subheader("3. Predictions")
    st.dataframe(result, use_container_width=True, hide_index=True)
    st.download_button(
        "Download predictions CSV",
        data=result.to_csv(index=False).encode("utf-8"),
        file_name="bean_predictions.csv",
        mime="text/csv"
    )

    if target_col not in data.columns:
        st.warning("The CSV does not contain the actual `Class` column. Predictions are available, but evaluation metrics and confusion matrix cannot be calculated.")
    else:
        y_true = data[target_col].astype(str).str.strip()
        y_pred = pd.Series(predictions).astype(str)
        classes = list(pipeline.named_steps["classifier"].classes_)
        probabilities = pipeline.predict_proba(X)

        # AUC needs at least two actual classes and compatible probability columns.
        try:
            auc = roc_auc_score(
                y_true, probabilities, labels=classes,
                multi_class="ovr", average="macro"
            )
        except ValueError:
            auc = None

        scores = {
            "Accuracy": accuracy_score(y_true, y_pred),
            "Precision": precision_score(y_true, y_pred, average="macro", zero_division=0),
            "Recall": recall_score(y_true, y_pred, average="macro", zero_division=0),
            "F1 Score": f1_score(y_true, y_pred, average="macro", zero_division=0),
            "MCC": matthews_corrcoef(y_true, y_pred),
        }
        st.subheader("4. Evaluation metrics")
        cols = st.columns(3)
        display_scores = [
            ("Accuracy", scores["Accuracy"]),
            ("AUC (macro OVR)", auc),
            ("Precision (macro)", scores["Precision"]),
            ("Recall (macro)", scores["Recall"]),
            ("F1 (macro)", scores["F1 Score"]),
            ("MCC", scores["MCC"]),
        ]
        for i, (label, value) in enumerate(display_scores):
            cols[i % 3].metric(label, "N/A" if value is None else f"{value:.4f}")

        st.subheader("5. Confusion matrix")
        cm = confusion_matrix(y_true, y_pred, labels=classes)
        fig, ax = plt.subplots(figsize=(9, 6))
        ConfusionMatrixDisplay(cm, display_labels=classes).plot(
            ax=ax, cmap="Blues", xticks_rotation=45, colorbar=False
        )
        ax.set_title(f"{model_name} — Confusion Matrix")
        fig.tight_layout()
        st.pyplot(fig)
        plt.close(fig)

        with st.expander("View classification report"):
            report = classification_report(
                y_true, y_pred, labels=classes, zero_division=0, output_dict=True
            )
            st.dataframe(pd.DataFrame(report).transpose(), use_container_width=True)
